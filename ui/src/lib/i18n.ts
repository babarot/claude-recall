export type Lang = "en" | "ja";

/** The page's language: Japanese when the browser's first language is, English otherwise. */
export function pickLang(languages: readonly string[]): Lang {
  return /^ja\b/i.test(languages[0] ?? "") ? "ja" : "en";
}

const browser = typeof navigator === "undefined" ? [] : navigator.languages?.length ? navigator.languages : [navigator.language];

export const lang: Lang = pickLang(browser);

export const t: typeof en = lang === "ja" ? ja : en;
